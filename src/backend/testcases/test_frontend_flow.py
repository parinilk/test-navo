#!/usr/bin/env python3
"""
Test script to simulate the actual frontend flow and show how context is stored
"""
import asyncio
import sys
import os
import json
from datetime import datetime

# Load environment variables from .env file first
try:
    from dotenv import load_dotenv
    env_path = os.path.join(os.path.dirname(__file__), '..', '.env')
    if os.path.exists(env_path):
        load_dotenv(env_path)
except ImportError:
    pass

# Add the backend directory to the path
sys.path.append(os.path.join(os.path.dirname(__file__), '..'))

from api.research import (
    save_research_session_fallback, 
    get_research_history_fallback,
    build_conversation_history,
    get_session_context_for_query
)
from rag.llm_integration import LLMService

async def test_frontend_flow():
    """Test the actual frontend flow - user fills context, asks queries, gets responses"""
    print("🖥️ Testing Frontend Flow - Real User Scenario")
    print("=" * 60)
    
    # Initialize LLM service
    llm_service = LLMService()
    
    # Simulate user session
    session_id = "user-session-123"  # This would be generated by frontend
    
    # Clear any existing session data
    try:
        from pathlib import Path
        sessions_dir = Path("data/sessions")
        if sessions_dir.exists():
            session_file = sessions_dir / f"{session_id}.json"
            if session_file.exists():
                session_file.unlink()
                print("🗑️ Cleared existing session data")
    except Exception as e:
        print(f"⚠️ Could not clear session data: {e}")
    
    try:
        # STEP 1: User fills out context questions in frontend
        print("\n📝 STEP 1: User Fills Out Context Questions")
        print("(This happens in the frontend form)")
        
        user_context = {
            "role": "Skincare Enthusiast",
            "objective": "Finding the best anti-aging products",
            "topic": "Anti-aging skincare routine"
        }
        
        print(f"✅ User context filled:")
        print(f"   Role: {user_context['role']}")
        print(f"   Objective: {user_context['objective']}")
        print(f"   Topic: {user_context['topic']}")
        
        # STEP 2: User asks first question
        print("\n💬 STEP 2: User Asks First Question")
        query1 = "What are the best anti-aging ingredients for my skin?"
        print(f"User asks: '{query1}'")
        
        # Backend processes query with context
        response1 = await llm_service.generate_research_response(
            query=query1,
            context=user_context,
            product_data=[],
            processed_query={"intent": "product_recommendation", "analysis_complexity": "medium"}
        )
        
        print(f"✅ LLM Response generated: {len(response1.get('answer', ''))} characters")
        print(f"   Answer preview: {response1.get('answer', '')[:100]}...")
        
        # Backend saves query + response + context to session
        await save_research_session_fallback(session_id, query1, response1, user_context)
        print("✅ Session saved with context")
        
        # STEP 3: User asks follow-up question
        print("\n💬 STEP 3: User Asks Follow-up Question")
        query2 = "How often should I use retinol?"
        print(f"User asks: '{query2}'")
        
        # Backend retrieves context and conversation history
        retrieved_context = await get_session_context_for_query(session_id, query2)
        conversation_history = await build_conversation_history(session_id)
        
        print(f"✅ Context retrieved: {retrieved_context}")
        print(f"✅ Conversation history: {len(conversation_history)} entries")
        
        # Backend processes follow-up with context
        response2 = await llm_service.generate_research_response(
            query=query2,
            context=retrieved_context or user_context,
            product_data=[],
            processed_query={"intent": "product_usage", "analysis_complexity": "medium"},
            conversation_history=conversation_history
        )
        
        print(f"✅ LLM Response generated: {len(response2.get('answer', ''))} characters")
        print(f"   Answer preview: {response2.get('answer', '')[:100]}...")
        
        # Backend saves follow-up to session
        await save_research_session_fallback(session_id, query2, response2, retrieved_context or user_context)
        print("✅ Follow-up session saved")
        
        # STEP 4: User asks another follow-up
        print("\n💬 STEP 4: User Asks Another Follow-up")
        query3 = "What about side effects?"
        print(f"User asks: '{query3}'")
        
        # Backend retrieves context again
        retrieved_context = await get_session_context_for_query(session_id, query3)
        conversation_history = await build_conversation_history(session_id)
        
        print(f"✅ Context retrieved: {retrieved_context}")
        print(f"✅ Conversation history: {len(conversation_history)} entries")
        
        # Backend processes with full context
        response3 = await llm_service.generate_research_response(
            query=query3,
            context=retrieved_context or user_context,
            product_data=[],
            processed_query={"intent": "safety_information", "analysis_complexity": "medium"},
            conversation_history=conversation_history
        )
        
        print(f"✅ LLM Response generated: {len(response3.get('answer', ''))} characters")
        print(f"   Answer preview: {response3.get('answer', '')[:100]}...")
        
        # Backend saves to session
        await save_research_session_fallback(session_id, query3, response3, retrieved_context or user_context)
        print("✅ Third query session saved")
        
        # STEP 5: Check what's stored in the session
        print("\n🔍 STEP 5: Check What's Stored in Session")
        final_session = await get_research_history_fallback(session_id)
        
        if final_session:
            print(f"✅ Final session has {len(final_session.queries)} queries")
            print("\n📚 All queries in session:")
            for i, query in enumerate(final_session.queries, 1):
                print(f"   Query {i}: {query['query']}")
                print(f"   Response: {query['response']['answer'][:50]}...")
                print(f"   Timestamp: {query['timestamp']}")
                print()
            
            # Show context storage
            print("📚 Context Storage in Session:")
            # The context is stored in the session data, let's check the raw file
            from pathlib import Path
            session_file = Path("data/sessions") / f"{session_id}.json"
            if session_file.exists():
                with open(session_file, 'r') as f:
                    session_data = json.load(f)
                
                context = session_data.get('context', {})
                print(f"   Number of context entries: {len(context)}")
                for key, value in context.items():
                    print(f"   {key}: {value}")
        
        print("\n🎉 Frontend Flow Test Completed!")
        print("=" * 60)
        print("✅ Context is stored with EVERY query and response")
        print("✅ Follow-up questions use the stored context")
        print("✅ LLM gets both context and conversation history")
        print("✅ Each query-response pair is saved to the session")
        
        return True
        
    except Exception as e:
        print(f"❌ Test failed with error: {e}")
        import traceback
        traceback.print_exc()
        return False

if __name__ == "__main__":
    asyncio.run(test_frontend_flow())
